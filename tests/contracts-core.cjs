const assert=require('node:assert/strict');
const c=require('../frontend/contracts-core.js');
const d=c.describe([{value:0},{value:2},{value:null},{value:4}], 'abundancias',4);
assert.equal(d.n,3); assert.equal(d.missing,1); assert.equal(d.mean,2); assert.equal(d.median,2); assert.equal(d.sd,2); assert.equal(d.coverage,75);
assert.equal(c.describe([{value:null}],'historico_caza',1).sum,null);
assert.equal(c.describe([{value:0}],'historico_caza',1).sum,0);
assert.equal(c.describe([{value:0}],'abundancias',1).sd,null);
assert.deepEqual(c.describe([{value:'constante'},{value:null}], 'tendencias',2).counts,{en_alza:0,decrecimiento:0,constante:1});
const sixTrends=c.describe([{value:'incierta'},{value:null}], 'tendencias',2,'seis_categorias');
assert.deepEqual(sixTrends.counts,{aumento_fuerte:0,aumento_moderado:0,estable:0,incierta:1,descenso_moderado:0,descenso_pronunciado:0});
assert.equal(sixTrends.missing,1);
assert.equal(c.changes([{ccaa_codigo:'01',value:12}],[{ccaa_codigo:'01',value:null}])[0].value,12);
assert.equal(c.changes([{ccaa_codigo:'01',value:12}],[{ccaa_codigo:'01',value:null}],['01'])[0].value,null);
assert.equal(c.changes([{ccaa_codigo:'01',value:null}],[{ccaa_codigo:'01',value:0}])[0].status,'Nuevo dato');
console.log('Descriptive statistics and preview checks passed.');
const communities=[{code:'01',name:'A'},{code:'02',name:'B'},{code:'03',name:'C'},{code:'04',name:'D'}];
const before=[{ccaa_codigo:'01',value:0},{ccaa_codigo:'02',value:10},{ccaa_codigo:'03',value:null}];
const after=[{ccaa_codigo:'01',value:0},{ccaa_codigo:'02',value:4},{ccaa_codigo:'03',value:7}];
const cmp=c.compare(before,after,communities,'abundancias');
assert.equal(cmp[0].paired,true);assert.equal(cmp[0].changed,false);assert.equal(cmp[0].delta,0);
assert.equal(cmp[1].delta,-6);assert.equal(cmp[2].delta,null);assert.equal(cmp[3].changed,null);
assert.equal(c.compare(after,before,communities,'abundancias')[1].delta,6);
const trends=c.compare([{ccaa_codigo:'01',value:'constante'}],[{ccaa_codigo:'01',value:'en_alza'}],communities,'tendencias');
assert.equal(trends[0].changed,true);assert.equal(trends[0].delta,null);assert.equal(trends[1].paired,false);
assert.deepEqual(c.domain([...before,...after]),[0,10]);assert.equal(c.domain([{value:null}]),null);
console.log('Interval comparison, shared domains, zero and missing-value checks passed.');
